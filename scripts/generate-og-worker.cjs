const fs = require('fs');
const path = require('path');

const postsDir = './src/data/posts';
const postFiles = fs.readdirSync(postsDir).filter(f => f.endsWith('.ts'));

const posts = {};

for (const file of postFiles) {
  const content = fs.readFileSync(path.join(postsDir, file), 'utf-8');

  const slugMatch = content.match(/slug:\s*["']([^"']+)["']/);
  if (!slugMatch) continue;
  const slug = slugMatch[1];

  const titleMatch = content.match(/title:\s*\n?\s*["'](.+?)["'],?\s*\n/s) ||
    content.match(/title:\s*["'](.+?)["']/);
  const title = titleMatch ? titleMatch[1].replace(/\s+/g, ' ').trim() : slug;

  const excerptMatch = content.match(/excerpt:\s*\n?\s*["'](.+?)["'],?\s*\n/s) ||
    content.match(/excerpt:\s*["'](.+?)["']/);
  const description = excerptMatch ? excerptMatch[1].replace(/\s+/g, ' ').trim() : '';

  const imageMatch = content.match(/ogImage:\s*["']([^"']+)["']/);
  const image = imageMatch ? imageMatch[1] : 'https://stefanosugbit.com/og-preview.png';

  posts[slug] = { title, description, image };
}

const workerCode = `// Auto-generated by GitHub Actions - DO NOT EDIT MANUALLY
// Last updated: ${new Date().toISOString()}

const BLOG_POSTS = ${JSON.stringify(posts, null, 2)};

const DEFAULT_OG = {
  title: "Stefanos Ugbit • Software Engineer & Published Author",
  description: "Full-stack software engineer and published author. Building reliable software with clean architecture, and writing poetry that explores personal growth.",
  image: "https://stefanosugbit.com/og-preview.png"
};

addEventListener("fetch", function(event) {
  event.respondWith(handleRequest(event.request));
});

async function handleRequest(request) {
  var url = new URL(request.url);
  var path = url.pathname;

  var blogMatch = path.match(/^\\/writing\\/([^\\/]+)\\/?$/);

  var response = await fetch(request);

  var contentType = response.headers.get("Content-Type") || "";
  if (!contentType.includes("text/html")) {
    return response;
  }

  var html = await response.text();

  var og = DEFAULT_OG;
  if (blogMatch) {
    var slug = blogMatch[1];
    if (BLOG_POSTS[slug]) {
      og = BLOG_POSTS[slug];
    }
  }

  html = html
    .replace(/<meta\\s+property="og:title"[\\s\\S]*?\\/>/, '<meta property="og:title" content="' + escapeHtml(og.title) + '" />')
    .replace(/<meta\\s+property="og:description"[\\s\\S]*?\\/>/, '<meta property="og:description" content="' + escapeHtml(og.description) + '" />')
    .replace(/<meta\\s+property="og:url"[\\s\\S]*?\\/>/, '<meta property="og:url" content="https://stefanosugbit.com' + path + '" />')
    .replace(/<meta\\s+property="og:image"[\\s\\S]*?\\/>/, '<meta property="og:image" content="' + og.image + '" />')
    .replace(/<meta\\s+name="twitter:title"[\\s\\S]*?\\/>/, '<meta name="twitter:title" content="' + escapeHtml(og.title) + '" />')
    .replace(/<meta\\s+name="twitter:description"[\\s\\S]*?\\/>/, '<meta name="twitter:description" content="' + escapeHtml(og.description) + '" />')
    .replace(/<meta\\s+name="twitter:url"[\\s\\S]*?\\/>/, '<meta name="twitter:url" content="https://stefanosugbit.com' + path + '" />')
    .replace(/<meta\\s+name="twitter:image"[\\s\\S]*?\\/>/, '<meta name="twitter:image" content="' + og.image + '" />')
    .replace(/<title>[^<]*<\\/title>/, blogMatch && BLOG_POSTS[blogMatch[1]]
      ? '<title>' + escapeHtml(og.title) + ' | Stefanos Ugbit</title>'
      : '<title>' + escapeHtml(og.title) + '</title>');

  if (blogMatch) {
    html = html.replace(/<meta\\s+property="og:type"[\\s\\S]*?\\/>/, '<meta property="og:type" content="article" />');
  }

  var status = blogMatch && BLOG_POSTS[blogMatch[1]] ? 200 : response.status;

  return new Response(html, {
    status: status,
    headers: { "Content-Type": "text/html;charset=UTF-8" }
  });
}

function escapeHtml(text) {
  return text
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}`;

fs.writeFileSync('worker-dist.js', workerCode);
console.log('Generated worker with', Object.keys(posts).length, 'posts');
